import fs from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { GUI_PACKAGE } from './rpc.js';

const requireBuild = createRequire(new URL('./build-tools/package.json', import.meta.url));
const { build } = requireBuild('esbuild');

/** Bundle actual module dependencies; never serialize function closures. */
export async function buildClient() {
  const result = await build({
    absWorkingDir: fileURLToPath(new URL('.', import.meta.url)),
    entryPoints: ['./client.source.js'], bundle: true, format: 'cjs', platform: 'browser',
    write: false, minify: true, legalComments: 'eof',
  });
  return `// Generated by tools/gui/build.mjs. Do not edit this artifact.\nwindow.__ModuleLoader__.load({id:${JSON.stringify(GUI_PACKAGE)},factory(require){const module={exports:{}};const exports=module.exports;\n${result.outputFiles[0].text}\nreturn module.exports.factory(require);}});\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const artifact = await buildClient();
  const target = new URL('./client.js', import.meta.url);
  if (process.argv.includes('--check')) {
    if (await fs.readFile(target, 'utf8') !== artifact) throw new Error('Client artifact is stale. Run npm run build:gui.');
    console.log('Client artifact matches its source.');
  } else {
    await fs.writeFile(target, artifact);
    console.log('Built the self-contained Client artifact.');
  }
}
